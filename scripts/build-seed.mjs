import { readFileSync, writeFileSync } from "node:fs";

const seed = JSON.parse(readFileSync(new URL("../data/seed/plants.json", import.meta.url), "utf8"));

const quote = (value) => {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
};

const rows = seed.plants.map((plant) => {
  const names = `ARRAY[${plant.alternative_names.map((name) => quote(name)).join(", ")}]::text[]`;
  const meta = `$meta$${JSON.stringify(plant.metadata)}$meta$::jsonb`;
  return `(${[
    quote(plant.id) + "::uuid",
    quote(plant.slug),
    quote(plant.genus),
    quote(plant.species),
    quote(plant.infraspecific_rank),
    quote(plant.infraspecific_epithet),
    quote(plant.cultivar),
    quote(plant.authority),
    quote(plant.family),
    names,
    quote(plant.origin),
    quote(plant.habitat),
    quote(plant.hardiness_zone),
    quote(plant.hardiness_rhs),
    meta,
  ].join(", ")})`;
});

const sql = `-- Generated by scripts/build-seed.mjs from data/seed/plants.json.
-- Original prose. Not RHS Plant Finder data. Seedlantern is a fictional cultivar.
INSERT INTO public.plants (
  id, slug, genus, species, infraspecific_rank, infraspecific_epithet,
  cultivar, authority, family, alternative_names, origin, habitat,
  hardiness_zone, hardiness_rhs, metadata
) VALUES
${rows.join(",\n")}
ON CONFLICT (slug) DO NOTHING;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql (${seed.plants.length} plants)`);
